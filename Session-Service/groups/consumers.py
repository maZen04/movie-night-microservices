    async def movie_liked(self, event):
        await self.send(
            text_data=json.dumps({
                "type": "movie_liked",
                "movie_id": event["movie_id"],
                "likes": event["likes"],
            })
        )
    
    async def movie_selected(self, event):

        await self.send(
            text_data=json.dumps({
                "type": "movie_selected",
                "movie": event["movie"],
            })
        )

        await self.close()

    async def no_winner(self, event):
        await self.send(
            text_data=json.dumps({
                "type": "no_winner",
            })
        )
        await self.close()

    async def member_joined(self, event):
        await self.send(
            text_data=json.dumps({
                "type": "member_joined",
                "user_id": event["user_id"],
            })
        )
    
    async def session_started(self, event):
        await self.send(
            text_data=json.dumps({
                "type": "session_started",
                "session_id": event["session_id"],
            })
        )
    
    async def session_ended(self, event):
        await self.send(
            text_data=json.dumps({
                "type": "session_ended",
                "movie_tmdb_id": event["movie_tmdb_id"],
            })
        )