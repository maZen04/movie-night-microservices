from channels.generic.websocket import WebsocketConsumer, AsyncWebsocketConsumer
import json
from urllib.parse import parse_qs
from channels.db import database_sync_to_async
from .models import *
from .services.vote_store import VoteStorageService

vote_storage = VoteStorageService()

class SessionConsumer(AsyncWebsocketConsumer):

    async def connect(self):
        self.session_id = self.scope["url_route"]["kwargs"]["session_id"]

        self.room_group_name = f"session_{self.session_id}"
        print("="*50)
        headers = dict(self.scope.get("headers", []))
        print("WEBSOCKET HEADERS:", headers)

        user_id = headers.get(b"x-user-id")

        print("USER ID FROM HEADER:", user_id)

        if not user_id:
            await self.close(code=4001)
            return

        self.user_id = int(user_id.decode())

        session = await database_sync_to_async(
            Session.objects.filter(id=self.session_id).first
        )()

        await self.accept()

        if not session:
            await self.send(
                text_data=json.dumps({
                    "type": "error",
                    "message": "Session not found."
                })
            )

            await self.close(code=4004)
            return
        
        if session.status != Session.Status.ACTIVE:
            await self.send(
                text_data=json.dumps({
                    "type": "error",
                    "message": "Session is not active."
                })
            )
            await self.close(code=4003)
            return

        participant = await database_sync_to_async(
            SessionParticipant.objects.filter(
                session=session,
                user_id=self.user_id
            ).exists
        )()

        if not participant:
            await self.send(
                text_data=json.dumps({
                    "type": "error",
                    "message": "You are not a participant in this session."
                })
            )
            await self.close(code=4001)
            return

        await self.channel_layer.group_add(
            self.room_group_name,
            self.channel_name, # automaticlly generated by the server 
        )

        

    async def disconnect(self, close_code):
        await self.channel_layer.group_discard(
            self.room_group_name,
            self.channel_name,
        )

